def categorize_item(item_name: str) -> str:
    """
    Определяет категорию предмета по названию.
    
    Args:
        item_name: Название предмета
        
    Returns:
        str: Ключ категории
    """
    item_name_lower = item_name.lower()
    
    for category, keywords in ITEM_CATEGORIES.items():
        for keyword in keywords:
            if keyword in item_name_lower:
                return category
    
    return "other"


def get_items_by_category(
    items_data: Dict[int, tuple],
    category: str
) -> Dict[int, tuple]:
    """
    Фильтрует предметы по категории.
    
    Args:
        items_data: {item_id: (item_name, prices)}
        category: Ключ категории или "all"
        
    Returns:
        Отфильтрованный словарь предметов
    """
    if category == "all":
        return items_data
    
    filtered = {}
    for item_id, (item_name, prices) in items_data.items():
        if categorize_item(item_name) == category:
            filtered[item_id] = (item_name, prices)
    
    return filtered


def get_all_categories() -> List[Dict[str, str]]:
    """
    Возвращает список всех категорий.
    
    Returns:
        Список словарей с ключом и названием категории
    """
    return [
        {"key": key, "name": CATEGORY_NAMES.get(key, key)}
        for key in CATEGORY_ORDER
    ]
